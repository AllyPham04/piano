r"""Condition C0 (``model_synth``): spectrograms generated by our own model (README §5.5).

The ground-truth notes (synthetic GT) are turned into an activation roll and
passed through the spectral model **at its initial physical parameters**
(δ = 0, B_p = 3e-4, ρ = 0.3). If the fit cannot recover these notes, there is a
bug or an identifiability problem (E0 sanity check, target onset F1 ≥ 0.95).

Activation of a note with velocity v and onset t_on, while it sounds:

.. math::  A_{p,t} = \text{amplitude} \cdot \frac{v}{127}\, e^{-(t - t_{on}) / \tau}

and 0 after its offset (agreed decision B1). The decay makes a re-struck key
show a rise in energy, as on a real piano; a binary roll would hide it.

The spectrogram is synthesised directly (no audio), so C0 is computed on the
fly from the GT CSV and never stored. A constant noise floor β is added.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import torch

from pianoabs.model.spectral_piano import SpectralPiano


def n_frames_for(cfg: dict) -> int:
    """T = 1 + floor(N / hop) for an excerpt of (excerpt + tail) seconds (center=True)."""
    d = cfg["data"]
    n_samples = int(round((d["excerpt_s"] + d["tail_s"]) * d["sample_rate"]))
    return 1 + n_samples // cfg["features"]["hop"]


def gt_activation_roll(notes: pd.DataFrame, n_frames: int, frame_s: float, tau_s: float,
                       pitch_min: int = 21, pitch_max: int = 108) -> np.ndarray:
    """Decaying activation roll (88, T) from GT notes; overlapping notes add."""
    times = np.arange(n_frames) * frame_s
    roll = np.zeros((pitch_max - pitch_min + 1, n_frames), dtype=np.float32)
    for onset, offset, pitch, velocity in zip(notes["onset_s"], notes["offset_s"],
                                              notes["pitch"], notes["velocity"]):
        if not pitch_min <= pitch <= pitch_max:
            continue
        on = (times >= onset) & (times < offset)
        roll[int(pitch) - pitch_min, on] += (velocity / 127.0) * np.exp(-(times[on] - onset) / tau_s)
    return roll


def synthesize_c0(notes: pd.DataFrame, cfg: dict) -> tuple[dict[int, torch.Tensor], np.ndarray]:
    """C0 spectrograms ``{n_fft: (F_r, T)}`` and the activation roll that generated them."""
    c0 = cfg["c0"]
    if c0["amplitude"] is None:
        raise ValueError("c0.amplitude is not set in the config")
    n_frames = n_frames_for(cfg)
    frame_s = cfg["features"]["hop"] / cfg["data"]["sample_rate"]
    roll = c0["amplitude"] * gt_activation_roll(notes, n_frames, frame_s, c0["tau_s"],
                                                cfg["model"]["pitch_min"], cfg["model"]["pitch_max"])
    # The data must not depend on the model variant being tested (e.g. B0 fits
    # C0 data generated *with* B = B_init), so B_mode is pinned to the default.
    data_cfg = {**cfg, "model": {**cfg["model"], "B_mode": "learned"}}
    model = SpectralPiano.from_config(data_cfg, n_frames)  # initial physical parameters
    A = torch.as_tensor(roll)
    with torch.no_grad():
        specs = {n: model.templates(n).T @ A + c0["beta"] for n in model.n_ffts}
    return specs, roll
